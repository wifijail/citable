export type LegalSlug = 'terms' | 'privacy' | 'cookies' | 'refund' | 'consent';

export const LEGAL_SLUGS: readonly LegalSlug[] = ['terms', 'privacy', 'cookies', 'refund', 'consent'];

export function isLegalSlug(value: string): value is LegalSlug {
  return (LEGAL_SLUGS as readonly string[]).includes(value);
}

export interface LegalContext {
  brand: string;
  siteUrl: string;
  /** Registered name, or null when not configured yet. */
  entity: string | null;
  registration: string | null;
  address: string | null;
  email: string | null;
  phone: string | null;
  refundDays: number;
  updated: string;
  dataLocation: string | null;
  consentVersion: string;
  /** "Gumroad", "Boosty"… or null when payments are not open. */
  paymentPlatform: string | null;
  retention: {
    ipHashHours: number;
    scanDays: number;
    checkoutDays: number;
    rejectedRequestDays: number;
    leadDays: number;
    contactDays: number;
  };
}

export interface LegalDocument {
  title: string;
  intro: string;
  sections: Array<{ heading: string; paragraphs: string[] }>;
}

interface LegalPack {
  translationNotice: string | null;
  updated: (date: string) => string;
  titles: Record<LegalSlug, string>;
  build: Record<LegalSlug, (c: LegalContext) => LegalDocument>;
}

