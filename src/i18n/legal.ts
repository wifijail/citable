/* ------------------------------------------------------------------ ru */

function ruOperator(c: LegalContext): string {
  if (!c.entity) return `владелец сайта ${c.siteUrl}`;
  const parts = [c.entity];
  if (c.registration) parts.push(`ИИН/БИН ${c.registration}`);
  if (c.address) parts.push(c.address);
  return parts.join(', ');
}

function ruContacts(c: LegalContext): string {
  const channels = [c.email && `почта ${c.email}`, c.phone && `телефон ${c.phone}`].filter(Boolean);
  const form = `форма на странице ${c.siteUrl}/ru/contact`;
  return channels.length ? `${channels.join(', ')}, ${form}` : form;
}

