function enOperator(c: LegalContext): string {
  if (!c.entity) return `the owner of ${c.siteUrl}`;
  const parts = [c.entity];
  if (c.registration) parts.push(`IIN/BIN ${c.registration}`);
  if (c.address) parts.push(c.address);
  return parts.join(', ');
}

function enContacts(c: LegalContext): string {
  const channels = [c.email && `email ${c.email}`, c.phone && `phone ${c.phone}`].filter(Boolean);
  const form = `the form at ${c.siteUrl}/en/contact`;
  return channels.length ? `${channels.join(', ')}, ${form}` : form;
}

