function kkOperator(c: LegalContext): string {
  if (!c.entity) return `${c.siteUrl} сайтының иесі`;
  const parts = [c.entity];
  if (c.registration) parts.push(`ЖСН/БСН ${c.registration}`);
  if (c.address) parts.push(c.address);
  return parts.join(', ');
}

function kkContacts(c: LegalContext): string {
  const channels = [c.email && `пошта ${c.email}`, c.phone && `телефон ${c.phone}`].filter(Boolean);
  const form = `${c.siteUrl}/kk/contact бетіндегі форма`;
  return channels.length ? `${channels.join(', ')}, ${form}` : form;
}

